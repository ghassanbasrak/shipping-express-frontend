import type {
  ShipmentFormValues,
  ShipmentReceiverValues,
} from "./ShipmentSchema";
import { defaultCountry, defaultCountryId, defaultCountryCode } from "../Utils";
export const newShipmentReceiver = (): ShipmentReceiverValues => ({
  key: crypto.randomUUID(),
  receiverId: "new",
  receiverName: "",
  receiverEmail: "",
  receiverPhone: "",
  receiverPhoneCountry: "+966",
  receiverPhone1: "",
  receiverPhoneCountry1: "+966",
  receiverCountryId: defaultCountryId,
  receiverCountryName: defaultCountry.name.en,
  receiverCountryCode: defaultCountryCode,
  receiverStateId: "",
  receiverCityId: "",
  receiverStateName: "",
  receiverCityName: "",
  receiverStreet: "",
  receiverZipCode: "",
  receiverNationalAddress: "",
});
export default function ShipmentModel(
  data: Partial<ShipmentFormValues> = {},
): ShipmentFormValues {
  return {
    ...structuredClone({
      shippingCompanyId: "",
      shippingCompany: null,
      method: "local",
      senderId: "new",
      senderNamePrefix: "متجر",
      senderName: "",
      senderEmail: "",
      senderPhone: "",
      senderPhoneCountry: "+966",
      senderPhone1: "",
      senderPhoneCountry1: "+966",
      senderCountryId: defaultCountryId,
      senderCountryName: defaultCountry.name.en,
      senderCountryCode: defaultCountryCode,
      senderStateId: "",
      senderCityId: "",
      senderStateName: "",
      senderCityName: "",
      senderStreet: "",
      senderZipCode: "",
      senderNationalAddress: "",
      ...newShipmentReceiver(),
      type: "box",
      length: 1,
      width: 1,
      height: 1,
      weight: 1,
      packagesCount: 1,
      description: "",
      isCommercial: false,
      imageUrl: "",
      acceptExtraWeightTerms: false,
      isCod: false,
      codPrice: 0,
      couponCode: "",
      couponCodeId: "",
      coupon: null,
      ...data,
    }),
    receivers: data.receivers
      ? structuredClone(data.receivers)
      : [newShipmentReceiver()],
  };
}
